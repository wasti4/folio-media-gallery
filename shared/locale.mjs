export function translate(language, message, values = {}) {
  const text = messages[message]?.[language === 'en' ? 0 : language === 'zh-CN' ? 1 : -1] ?? message
  return text.replace(/{(\w+)}/g, (match, key) => values[key] ?? match)
}

export function translateError(language, error, fallback = 'Попробуйте ещё раз.') {
  const raw = (error?.message || fallback).replace(/^Error invoking remote method '[^']+': Error: /, '')
  if (raw.includes('ENOSPC')) return translate(language, 'Недостаточно места на диске.')
  for (const pattern of [
    'Недоступен файл «{name}». Подключите диск и повторите.',
    'Проверьте целостность файла «{name}».',
    'Файл «{name}» изменился во время копирования. Повторите операцию.',
  ]) {
    const variant = raw.replace(/«[^»]+»/, '«{name}»')
    if (variant === pattern) return translate(language, pattern, { name: /«([^»]+)»/.exec(raw)?.[1] })
  }
  return translate(language, raw)
}
